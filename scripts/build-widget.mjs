// Builds the website widget as a versioned file plus a tiny loader.
//
//   public/widget/widget.<hash>.js  the widget, named by its content, cached for a year
//   public/widget.js                the loader customers embed; cached 5 minutes, it only
//                                   adds the current versioned file with the same data-key
//
// The last few versions are kept so a page that still has the previous loader cached keeps
// working right after a deploy. Edit resources/widget/widget.js, then run npm run build:widget.

import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, statSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const KEEP_VERSIONS = 3;
const outDir = 'public/widget';
const banner = '/* Botzo widget. Built from resources/widget/widget.js, edit that file and run npm run build:widget. */';

const result = await build({
    entryPoints: ['resources/widget/widget.js'],
    bundle: false,
    minify: true,
    target: 'es2017',
    charset: 'utf8',
    legalComments: 'none',
    banner: { js: banner },
    write: false,
});
const code = result.outputFiles[0].text;
const hash = createHash('sha256').update(code).digest('hex').slice(0, 10);
const name = `widget.${hash}.js`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, name), code);

const versions = readdirSync(outDir)
    .filter((file) => /^widget\.[0-9a-f]{10}\.js$/.test(file))
    .map((file) => ({ file, time: file === name ? Infinity : statSync(join(outDir, file)).mtimeMs }))
    .sort((a, b) => b.time - a.time);
versions.slice(KEEP_VERSIONS).forEach(({ file }) => unlinkSync(join(outDir, file)));

const loader = await build({
    stdin: {
        contents: `(function () {
    var current = document.currentScript || document.querySelector('script[data-key][src*="widget.js"]');
    if (!current || window.__botzoWidgetLoader) {
        return;
    }
    window.__botzoWidgetLoader = true;
    var script = document.createElement('script');
    script.src = new URL('/widget/${name}', current.src).href;
    script.async = true;
    script.setAttribute('data-key', current.getAttribute('data-key') || '');
    (document.head || document.documentElement).appendChild(script);
})();`,
        loader: 'js',
    },
    minify: true,
    target: 'es2017',
    legalComments: 'none',
    banner: { js: '/* Botzo widget loader: loads the current versioned widget. Generated by scripts/build-widget.mjs. */' },
    write: false,
});
writeFileSync('public/widget.js', loader.outputFiles[0].text);

// Added by the snippet in Salla stores; finds the store's widget key, then adds public/widget.js.
const sallaLoader = await build({
    entryPoints: ['resources/widget/salla-loader.js'],
    minify: true,
    target: 'es2017',
    legalComments: 'none',
    banner: { js: '/* Botzo loader for Salla stores. Built from resources/widget/salla-loader.js. */' },
    write: false,
});
writeFileSync('public/salla-widget.js', sallaLoader.outputFiles[0].text);

// The merchant's panel inside Salla's dashboard, with Salla's SDK bundled in.
const sallaPanel = await build({
    entryPoints: ['resources/widget/salla-panel.js'],
    bundle: true,
    format: 'iife',
    minify: true,
    target: 'es2019',
    charset: 'utf8',
    legalComments: 'none',
    banner: { js: '/* Botzo panel for Salla. Built from resources/widget/salla-panel.js. */' },
    write: false,
});
writeFileSync('public/salla-panel.js', sallaPanel.outputFiles[0].text);
console.log(`salla panel: public/salla-panel.js (${sallaPanel.outputFiles[0].text.length} bytes)`);

console.log(`widget: ${outDir}/${name} (${code.length} bytes), loader public/widget.js (${loader.outputFiles[0].text.length} bytes)`);
